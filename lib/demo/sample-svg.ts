import { formatDate, formatINR } from "../format";
import type { SampleBill } from "./sample-bills";

const esc = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const W = 600;
const H = 820;
const FONT = "font-family='Helvetica, Arial, sans-serif'";

/** Renders a sample bill as a watermarked SVG "scan". The numbers come from the same data the demo shows. */
export function renderSampleSvg(bill: SampleBill): string {
  const x = bill.extraction;
  const v = <T,>(f: { value: T | null }, fallback = "") => (f.value === null ? fallback : f.value);
  const rows = x.lineItems
    .map((l, i) => {
      const y = 360 + i * 34;
      return `
    <text x="40" y="${y}" font-size="13">${esc(l.description)}</text>
    <text x="370" y="${y}" font-size="13" text-anchor="end">${l.quantity ?? ""} ${esc(l.unit ?? "")}</text>
    <text x="460" y="${y}" font-size="13" text-anchor="end">${l.unitPrice !== null ? esc(formatINR(l.unitPrice)) : ""}</text>
    <text x="560" y="${y}" font-size="13" text-anchor="end">${l.amount !== null ? esc(formatINR(l.amount)) : ""}</text>
    <line x1="40" y1="${y + 12}" x2="560" y2="${y + 12}" stroke="#0A0A0A" stroke-opacity="0.12"/>`;
    })
    .join("");

  const totalsY = 380 + x.lineItems.length * 34;
  const money = (n: number | null) => (n === null ? "" : esc(formatINR(n)));

  const watermark = Array.from({ length: 5 }, (_, i) =>
    `<text x="${W / 2}" y="${140 + i * 160}" font-size="44" font-weight="700" text-anchor="middle" fill="#FF5A1F" fill-opacity="0.16" transform="rotate(-28 ${W / 2} ${140 + i * 160})" letter-spacing="6">SAMPLE · NOT A REAL BILL</text>`,
  ).join("");

  const sheet = `
  <g ${FONT} fill="#0A0A0A">
    <rect width="${W}" height="${H}" fill="#FFFFFF"/>
    <text x="40" y="70" font-size="22" font-weight="700">${esc(String(v(x.vendorName)))}</text>
    <text x="40" y="94" font-size="12" fill-opacity="0.6">${esc(bill.address)}</text>
    <text x="40" y="114" font-size="12" font-family="Courier New, monospace">GSTIN ${esc(String(v(x.vendorGstin)))}</text>
    <text x="560" y="70" font-size="16" font-weight="700" text-anchor="end">TAX INVOICE</text>
    <text x="560" y="94" font-size="12" text-anchor="end" font-family="Courier New, monospace">${esc(String(v(x.invoiceNumber)))}</text>
    <text x="560" y="114" font-size="12" text-anchor="end">Date: ${esc(formatDate(String(v(x.invoiceDate))))}</text>
    <line x1="40" y1="140" x2="560" y2="140" stroke="#0A0A0A"/>
    <text x="40" y="172" font-size="11" fill-opacity="0.6">BILL TO</text>
    <text x="40" y="192" font-size="13">Sunrise Constructions (sample buyer)</text>
    <text x="40" y="212" font-size="12" fill-opacity="0.6">Your PO: ${esc(String(v(x.poNumber, "-")))}</text>
    <text x="560" y="192" font-size="13" text-anchor="end" font-style="italic">Terms: ${esc(bill.terms)}</text>
    <rect x="40" y="310" width="520" height="28" fill="#0A0A0A" fill-opacity="0.05"/>
    <text x="48" y="329" font-size="11" font-weight="700">ITEM</text>
    <text x="370" y="329" font-size="11" font-weight="700" text-anchor="end">QTY</text>
    <text x="460" y="329" font-size="11" font-weight="700" text-anchor="end">RATE</text>
    <text x="560" y="329" font-size="11" font-weight="700" text-anchor="end">AMOUNT</text>
    ${rows}
    <text x="440" y="${totalsY + 20}" font-size="13" text-anchor="end" fill-opacity="0.6">Subtotal</text>
    <text x="560" y="${totalsY + 20}" font-size="13" text-anchor="end">${money(x.subtotal.value)}</text>
    <text x="440" y="${totalsY + 42}" font-size="13" text-anchor="end" fill-opacity="0.6">CGST 9%</text>
    <text x="560" y="${totalsY + 42}" font-size="13" text-anchor="end">${money(x.cgst.value)}</text>
    <text x="440" y="${totalsY + 64}" font-size="13" text-anchor="end" fill-opacity="0.6">SGST 9%</text>
    <text x="560" y="${totalsY + 64}" font-size="13" text-anchor="end">${money(x.sgst.value)}</text>
    <line x1="340" y1="${totalsY + 78}" x2="560" y2="${totalsY + 78}" stroke="#0A0A0A"/>
    <text x="440" y="${totalsY + 100}" font-size="15" font-weight="700" text-anchor="end">Total</text>
    <text x="560" y="${totalsY + 100}" font-size="15" font-weight="700" text-anchor="end">${money(x.total.value)}</text>
    <text x="40" y="${H - 40}" font-size="10" fill-opacity="0.5">Fictional vendor and buyer. Generated by Hisaab AI for demonstration only.</text>
    ${watermark}
  </g>`;

  if (!bill.photo) {
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">${sheet}<rect width="${W}" height="${H}" fill="none" stroke="#0A0A0A" stroke-opacity="0.2"/></svg>`;
  }

  // "Phone photo": dark table background, tilted sheet, uneven lighting.
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <defs>
    <linearGradient id="glare" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.5"/>
      <stop offset="0.4" stop-color="#FFFFFF" stop-opacity="0"/>
      <stop offset="1" stop-color="#000000" stop-opacity="0.18"/>
    </linearGradient>
  </defs>
  <rect width="${W}" height="${H}" fill="#5B4A3A"/>
  <g transform="translate(${W / 2} ${H / 2}) rotate(-3) scale(0.9) translate(${-W / 2} ${-H / 2})">
    ${sheet}
    <rect width="${W}" height="${H}" fill="url(#glare)"/>
  </g>
</svg>`;
}
